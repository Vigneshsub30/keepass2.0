    /// <summary>
    /// xUnit promotion of the ChaCha20 self-test vectors from SelfTest.TestChaCha20().
    /// RFC 8439 sections 2.3.2 and 2.4.2, plus Strombergson TC8.
    /// </summary>
    public class ChaCha20Tests
    {
        // ── RFC 8439 section 2.3.2 ──────────────────────────────────────────
        // Key: bytes 0..31; IV: [3]=0x09, [7]=0x4A; skip first block, read block 2
        [Fact]
        public void ChaCha20_Rfc8439_Section232_SecondBlockVector()
        {
            byte[] pbKey = new byte[32];
            for (int i = 0; i < 32; ++i) pbKey[i] = (byte)i;

            byte[] pbIV = new byte[12];
            pbIV[3] = 0x09;
            pbIV[7] = 0x4A;

            byte[] pbExpected = new byte[64]
            {
                0x10, 0xF1, 0xE7, 0xE4, 0xD1, 0x3B, 0x59, 0x15,
                0x50, 0x0F, 0xDD, 0x1F, 0xA3, 0x20, 0x71, 0xC4,
                0xC7, 0xD1, 0xF4, 0xC7, 0x33, 0xC0, 0x68, 0x03,
                0x04, 0x22, 0xAA, 0x9A, 0xC3, 0xD4, 0x6C, 0x4E,
                0xD2, 0x82, 0x64, 0x46, 0x07, 0x9F, 0xAA, 0x09,
                0x14, 0xC2, 0xD7, 0x05, 0xD9, 0x8B, 0x02, 0xA2,
                0xB5, 0x12, 0x9C, 0xD1, 0xDE, 0x16, 0x4E, 0xB9,
                0xCB, 0xD0, 0x83, 0xE8, 0xA2, 0x50, 0x3C, 0x4E
            };

            byte[] pb = new byte[64];
            using (ChaCha20Cipher c = new ChaCha20Cipher(pbKey, pbIV))
            {
                c.Seek(64, SeekOrigin.Begin); // Skip first block (counter=0)
                c.Encrypt(pb, 0, pb.Length);
            }

            Assert.Equal(pbExpected, pb);
        }

        // ── RFC 8439 section 2.4.2 ──────────────────────────────────────────
        // Encrypt "Ladies and Gentlemen..." plaintext starting at counter=1
        [Fact]
        public void ChaCha20_Rfc8439_Section242_SunscreenPlaintext()
        {
            byte[] pbKey = new byte[32];
            for (int i = 0; i < 32; ++i) pbKey[i] = (byte)i;

            byte[] pbIV = new byte[12]; // all zeros (counter reset to 0)

            byte[] pb = StrUtil.Utf8.GetBytes(
                "Ladies and Gentlemen of the class of '99: If I could offer you " +
                "only one tip for the future, sunscreen would be it.");

            byte[] pbExpected = new byte[]
            {
                0x6E, 0x2E, 0x35, 0x9A, 0x25, 0x68, 0xF9, 0x80,
                0x41, 0xBA, 0x07, 0x28, 0xDD, 0x0D, 0x69, 0x81,
                0xE9, 0x7E, 0x7A, 0xEC, 0x1D, 0x43, 0x60, 0xC2,
                0x0A, 0x27, 0xAF, 0xCC, 0xFD, 0x9F, 0xAE, 0x0B,
                0xF9, 0x1B, 0x65, 0xC5, 0x52, 0x47, 0x33, 0xAB,
                0x8F, 0x59, 0x3D, 0xAB, 0xCD, 0x62, 0xB3, 0x57,
                0x16, 0x39, 0xD6, 0x24, 0xE6, 0x51, 0x52, 0xAB,
                0x8F, 0x53, 0x0C, 0x35, 0x9F, 0x08, 0x61, 0xD8,
                0x07, 0xCA, 0x0D, 0xBF, 0x50, 0x0D, 0x6A, 0x61,
                0x56, 0xA3, 0x8E, 0x08, 0x8A, 0x22, 0xB6, 0x5E,
                0x52, 0xBC, 0x51, 0x4D, 0x16, 0xCC, 0xF8, 0x06,
                0x81, 0x8C, 0xE9, 0x1A, 0xB7, 0x79, 0x37, 0x36,
                0x5A, 0xF9, 0x0B, 0xBF, 0x74, 0xA3, 0x5B, 0xE6,
                0xB4, 0x0B, 0x8E, 0xED, 0xF2, 0x78, 0x5E, 0x42,
                0x87, 0x4D
            };

            byte[] pb64 = new byte[64];
            using (ChaCha20Cipher c = new ChaCha20Cipher(pbKey, pbIV))
            {
                c.Encrypt(pb64, 0, pb64.Length); // Skip first block (counter=0)
                c.Encrypt(pb, 0, pb.Length);     // Encrypt plaintext at counter=1
            }

            Assert.Equal(pbExpected, pb);
        }

        // ── Strombergson TC8 (original Bernstein variant, large counter) ─────
        [Fact]
        public void ChaCha20_StrombergsonTC8_LargeCounterDecryptVector()
        {
            byte[] pbKey = new byte[32]
            {
                0xC4, 0x6E, 0xC1, 0xB1, 0x8C, 0xE8, 0xA8, 0x78,
                0x72, 0x5A, 0x37, 0xE7, 0x80, 0xDF, 0xB7, 0x35,
                0x1F, 0x68, 0xED, 0x2E, 0x19, 0x4C, 0x79, 0xFB,
                0xC6, 0xAE, 0xBE, 0xE1, 0xA6, 0x67, 0x97, 0x5D
            };

            // First 4 bytes = 0 (large-counter flag); last 8 = 64-bit nonce
            byte[] pbIV = new byte[12]
            {
                0x00, 0x00, 0x00, 0x00,
                0x1A, 0xDA, 0x31, 0xD5, 0xCF, 0x68, 0x82, 0x21
            };

            byte[] pb = new byte[128]; // all zeros → XOR produces pure keystream

            byte[] pbExpected = new byte[128]
            {
                0xF6, 0x3A, 0x89, 0xB7, 0x5C, 0x22, 0x71, 0xF9,
                0x36, 0x88, 0x16, 0x54, 0x2B, 0xA5, 0x2F, 0x06,
                0xED, 0x49, 0x24, 0x17, 0x92, 0x30, 0x2B, 0x00,
                0xB5, 0xE8, 0xF8, 0x0A, 0xE9, 0xA4, 0x73, 0xAF,
                0xC2, 0x5B, 0x21, 0x8F, 0x51, 0x9A, 0xF0, 0xFD,
                0xD4, 0x06, 0x36, 0x2E, 0x8D, 0x69, 0xDE, 0x7F,
                0x54, 0xC6, 0x04, 0xA6, 0xE0, 0x0F, 0x35, 0x3F,
                0x11, 0x0F, 0x77, 0x1B, 0xDC, 0xA8, 0xAB, 0x92,
                0xE5, 0xFB, 0xC3, 0x4E, 0x60, 0xA1, 0xD9, 0xA9,
                0xDB, 0x17, 0x34, 0x5B, 0x0A, 0x40, 0x27, 0x36,
                0x85, 0x3B, 0xF9, 0x10, 0xB0, 0x60, 0xBD, 0xF1,
                0xF8, 0x97, 0xB6, 0x29, 0x0F, 0x01, 0xD1, 0x38,
                0xAE, 0x2C, 0x4C, 0x90, 0x22, 0x5B, 0xA9, 0xEA,
                0x14, 0xD5, 0x18, 0xF5, 0x59, 0x29, 0xDE, 0xA0,
                0x98, 0xCA, 0x7A, 0x6C, 0xCF, 0xE6, 0x12, 0x27,
                0x05, 0x3C, 0x84, 0xE4, 0x9A, 0x4A, 0x33, 0x32
            };

            // bLargeCounter=true: uses original Bernstein counter layout
            using (ChaCha20Cipher c = new ChaCha20Cipher(pbKey, pbIV, true))
            {
                c.Decrypt(pb, 0, pb.Length);
            }

            Assert.Equal(pbExpected, pb);
        }
    }
